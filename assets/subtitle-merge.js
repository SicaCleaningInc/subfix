/*
 * ZimuFix — 雙語字幕合併核心
 * 以「主字幕」嘅時間為準，搵出時間重疊嘅「第二字幕」句子合併。
 * 依賴 subtitle-format.js 嘅 parse()。
 */
(function (root) {
  'use strict';

  function clean(text, oneLine) {
    var t = text.replace(/<[^>]+>/g, '').replace(/\{[^}]*\}/g, '');
    var lines = t.split('\n').map(function (l) { return l.trim(); }).filter(Boolean);
    return oneLine ? lines.join(' ') : lines.join('\n');
  }

  function overlap(a, b) { return Math.min(a.end, b.end) - Math.max(a.start, b.start); }

  /**
   * primary, secondary：[{start, end, text}]
   * opts.oneLine：每種語言合併為一行；opts.keepUnmatched：保留配對唔到嘅第二字幕
   * 回傳 [{start, end, a, b}]，a = 主字幕文字，b = 第二字幕文字（可能為空）
   */
  function merge(primary, secondary, opts) {
    opts = opts || {};
    var used = new Array(secondary.length);
    var out = [];
    var j0 = 0;
    primary.forEach(function (p) {
      var hits = [];
      while (j0 < secondary.length && secondary[j0].end <= p.start) j0++;
      for (var j = Math.max(0, j0 - 3); j < secondary.length && secondary[j].start < p.end; j++) {
        var s = secondary[j];
        var ov = overlap(p, s);
        if (ov <= 0) continue;
        var shorter = Math.max(1, Math.min(p.end - p.start, s.end - s.start));
        if (ov / shorter >= 0.3) { hits.push(j); }
      }
      hits.forEach(function (j) { used[j] = true; });
      out.push({
        start: p.start, end: p.end,
        a: clean(p.text, opts.oneLine),
        b: hits.map(function (j) { return clean(secondary[j].text, opts.oneLine); }).join(opts.oneLine ? ' ' : '\n')
      });
    });
    if (opts.keepUnmatched !== false) {
      secondary.forEach(function (s, j) {
        if (!used[j]) out.push({ start: s.start, end: s.end, a: '', b: clean(s.text, opts.oneLine) });
      });
      out.sort(function (x, y) { return x.start - y.start || x.end - y.end; });
    }
    return out.filter(function (c) { return c.a || c.b; });
  }

  function pad(n, w) { n = String(n); while (n.length < w) n = '0' + n; return n; }
  function srtTime(ms) {
    ms = Math.max(0, Math.round(ms));
    var h = Math.floor(ms / 3600000); ms -= h * 3600000;
    var m = Math.floor(ms / 60000); ms -= m * 60000;
    var s = Math.floor(ms / 1000); ms -= s * 1000;
    return pad(h, 2) + ':' + pad(m, 2) + ':' + pad(s, 2) + ',' + pad(ms, 3);
  }
  function assTime(ms) {
    var cs = Math.max(0, Math.round(ms / 10));
    var h = Math.floor(cs / 360000); cs -= h * 360000;
    var m = Math.floor(cs / 6000); cs -= m * 6000;
    var s = Math.floor(cs / 100); cs -= s * 100;
    return h + ':' + pad(m, 2) + ':' + pad(s, 2) + '.' + pad(cs, 2);
  }

  function lines(c, topFirst) {
    return (topFirst === 'b' ? [c.b, c.a] : [c.a, c.b]).filter(Boolean);
  }

  function toSRT(cues, topFirst) {
    return cues.map(function (c, i) {
      return (i + 1) + '\n' + srtTime(c.start) + ' --> ' + srtTime(c.end) + '\n' + lines(c, topFirst).join('\n');
    }).join('\n\n') + '\n';
  }

  /** ASS：上行用 Top 樣式（大字白色），下行用 Bottom 樣式（細字淺黃色） */
  function toASS(cues, topFirst, style) {
    style = style || {};
    var font = style.font || 'Microsoft JhengHei';
    var head = [
      '[Script Info]', '; Generated by ZimuFix (zimufix.com)', 'ScriptType: v4.00+', 'PlayResX: 1920', 'PlayResY: 1080',
      'WrapStyle: 0', 'ScaledBorderAndShadow: yes', '',
      '[V4+ Styles]',
      'Format: Name, Fontname, Fontsize, PrimaryColour, SecondaryColour, OutlineColour, BackColour, Bold, Italic, Underline, StrikeOut, ScaleX, ScaleY, Spacing, Angle, BorderStyle, Outline, Shadow, Alignment, MarginL, MarginR, MarginV, Encoding',
      'Style: Top,' + font + ',' + (style.topSize || 64) + ',&H00FFFFFF,&H000000FF,&H00000000,&H64000000,0,0,0,0,100,100,0,0,1,3,1,2,40,40,48,1',
      'Style: Bottom,' + font + ',' + (style.bottomSize || 46) + ',&H0080F0FF,&H000000FF,&H00000000,&H64000000,0,0,0,0,100,100,0,0,1,2.5,1,2,40,40,48,1',
      '', '[Events]',
      'Format: Layer, Start, End, Style, Name, MarginL, MarginR, MarginV, Effect, Text'
    ];
    var body = cues.map(function (c) {
      var ls = lines(c, topFirst).map(function (t) { return t.replace(/\n/g, '\\N'); });
      var text = ls.length === 2 ? ls[0] + '\\N{\\rBottom}' + ls[1] : ls[0];
      var st = (ls.length === 1 && (topFirst === 'b' ? !c.b : !c.a)) ? 'Bottom' : 'Top';
      return 'Dialogue: 0,' + assTime(c.start) + ',' + assTime(c.end) + ',' + st + ',,0,0,0,,' + text;
    });
    return head.concat(body).join('\n') + '\n';
  }

  var api = { merge: merge, toSRT: toSRT, toASS: toASS };
  if (typeof module !== 'undefined' && module.exports) module.exports = api;
  else root.ZimuMerge = api;
})(this);
